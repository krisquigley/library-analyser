class PlaylistRecipeRegressionTests(unittest.TestCase):
    def test_playlists_match_those_main_generated_before_the_refactor(self):
        library = synthetic_playlist_library()
        for (start, name, unit), expected in EXPECTED.items():
            options = RECIPES[name]
            length = {'length': 12} if unit == 'tracks' else {'duration_minutes': 60}
            recipe = PlaylistRecipe(start_track_id=start, bpm_min=100, bpm_max=140, **length, **options)
            with self.subTest(start=start, recipe=name, unit=unit):
                result = GenerateBpmGraphM3UPlaylist(library).execute(recipe)
                self.assertEqual(expected, ' '.join(track_id[1:] for track_id in result.track_ids))


