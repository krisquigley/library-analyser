HELPERS = r'''
const controlListeners=new Map();
controls.addEventListener=(name,callback)=>controlListeners.set(name,callback);
controls.removeEventListener=(name,callback)=>{if(controlListeners.get(name)===callback) controlListeners.delete(name);};
function orbit(position,target) {
  controlListeners.get('start')?.();
  Object.assign(camera.position,position); Object.assign(controls.target,target);
}
function configureView() {
  Object.assign(camera.position,{x:420,y:-480,z:150});
  Object.assign(controls.target,{x:120,y:-80,z:30});
  Object.assign(controls,{minDistance:350,maxDistance:600}); camera.zoom=3.25;
}
function pose() {return {position:{...camera.position},target:{...controls.target},
  zoom:camera.zoom,fov:camera.fov,minDistance:controls.minDistance,maxDistance:controls.maxDistance};}
function translated(before,node) {
  const target={x:node.fx,y:node.fy,z:node.fz};
  const position=Object.fromEntries(['x','y','z'].map(axis=>
    [axis,target[axis]+before.position[axis]-before.target[axis]]));
  return {...before,position,target};
}
function assertImmediate(before,node) {
  assert.deepEqual(pose(),translated(before,node),
    'graph click must synchronously translate camera AND orbit target, preserving direction, distance, zoom and custom bounds');
  assert.ok(calls.every(call=>call.duration===0),'no vendor animation for graph click');
}
function accept(id) {return {ok:true,json:async()=>({current_track_id:id,history:[],selection_epoch:0})};}
async function flush() {for(let i=0;i<12;i++) await Promise.resolve();}
function searchButton(id) {
  elements.tracks=new Element(); context.searchTracks=[{handle:id,title:id,artist:'fixture'}];
  run('renderTracks(searchTracks)');
  const table=elements.tracks.children[0], tbody=table.children[2];
  const button=tbody.children[0].children[0].children[0];
  assert.equal(typeof button.onclick,'function','real search row wires selection');
  return button;
}
'''


def node_limits():
    # No scratch data is generated by the scenario; bound diagnostics as well.
    resource.setrlimit(resource.RLIMIT_FSIZE, (1024 * 1024, 1024 * 1024))
    resource.setrlimit(resource.RLIMIT_CPU, (10, 10))


class GraphClickImmediateTests(unittest.TestCase):
    def run_scenario(self, scenario):
        node = shutil.which('node')
        self.assertIsNotNone(node, 'Node required: RED cannot be reported from skipped tests')
        script = (FIXTURE + HELPERS + scenario +
                  '\n})().then(()=>console.log("SCENARIO_COMPLETED")).catch(error=>{console.error(error);process.exitCode=1;});')
        for asset in ASSETS:
            with self.subTest(asset=str(asset.relative_to(ROOT))):
                with tempfile.TemporaryDirectory(prefix='issue84-click-') as scratch:
                    with (Path(scratch) / 'node.log').open('w+') as output:
                        process = subprocess.Popen([node, '-e', script, str(asset)], cwd=ROOT,
                                                   stdout=output, stderr=subprocess.STDOUT,
                                                   env={**os.environ, 'NODE_OPTIONS':
                                                        os.environ.get('NODE_OPTIONS', '') + ' --max-old-space-size=256'},
                                                   start_new_session=True, preexec_fn=node_limits)
                        try:
                            process.wait(timeout=15)
                        except subprocess.TimeoutExpired:
                            os.killpg(process.pid, signal.SIGKILL)
                            process.wait()
                            self.fail('Node scenario exceeded 15 seconds; process group killed')
                        finally:
                            # Also clean up descendants if the parent exits normally.
                            try:
                                os.killpg(process.pid, signal.SIGKILL)
                            except ProcessLookupError:
                                pass
                        output.seek(0)
                        diagnostic = output.read()
                self.assertEqual(process.returncode, 0, diagnostic)
                self.assertIn('SCENARIO_COMPLETED', diagnostic,
                              'Node exited without completing the bounded async scenario')

    def test_click_centers_synchronously_while_post_pending_without_replay_and_search_animates(self):
        self.run_scenario(r'''
render(); configureView(); calls.length=0;
const before=pose(), original=liveData, count=replacements;
let resolvePost;
postHook=()=>new Promise(resolve=>{resolvePost=resolve;});
const pending=clickHandler(liveData.nodes.find(n=>n.id==='b'));
assertImmediate(before,b);
assert.deepEqual(details,[],'pending POST does not authorize detail');
const clicked=pose(), clickedCalls=calls.length; tick(); tick();
assert.deepEqual(pose(),clicked,'unresolved POST cannot start an animation');
assert.equal(calls.length,clickedCalls,'no graph-click camera frames');
resolvePost(accept('b')); await pending; await flush(); tick(); tick();
assert.deepEqual(details,['b']); assertHalo('b');
assert.equal(calls.length,clickedCalls,'accepted click must not replay animated focus');
assert.deepEqual(pose(),clicked); assert.strictEqual(liveData,original);
assert.equal(replacements,count,'click selection preserves live topology');
// Execute the real rendered search-row callback, preserving #70's accepted path.
const button=searchButton('a'); postHook=()=>new Promise(resolve=>{resolvePost=resolve;});
const search=button.onclick(); const searchBefore=pose(); tick();
assert.deepEqual(pose(),searchBefore,'search does not center while POST is pending');
resolvePost(accept('a')); await search; await flush();
assert.deepEqual(pose(),searchBefore,'accepted search waits for its animation frame');
tick(); tick(); assert.equal(calls.length,clickedCalls+1,'search still owns its animated focus');
assert.deepEqual(controls.target,{x:a.fx,y:a.fy,z:a.fz});
const radius=Math.hypot(camera.position.x-a.fx,camera.position.y-a.fy,camera.position.z-a.fz);
assert.ok(Math.abs(radius-350)<1e-9,'existing search radius respects custom minimum');
assert.equal(camera.zoom,3.25); assertHalo('a');
''')

    def test_latest_click_search_and_orbit_ownership_ignore_out_of_order_posts(self):
        self.run_scenario(r'''
render(); configureView(); calls.length=0;
// Independent baseline-green control runs before any new-behavior assertion.
await searchButton('a').onclick(); await flush();
assert.equal(calls.length,0,'accepted search waits for animation frame');
tick(); tick(); assert.equal(calls.length,1,'real search callback retains accepted animated path');
assert.deepEqual(controls.target,{x:a.fx,y:a.fy,z:a.fz}); assertHalo('a');
configureView(); calls.length=0; details.length=0;
const pendingPosts=[]; postHook=id=>new Promise(resolve=>pendingPosts.push({id,resolve}));
const first=clickHandler(a);
const beforeB=pose(), second=clickHandler(b);
const bPose=translated(beforeB,b), clickCalls=calls.length;
pendingPosts[1].resolve(accept('b')); await second; await flush(); tick(); tick();
pendingPosts[0].resolve(accept('a')); await first; await flush(); tick(); tick();
assert.deepEqual(details,['b'],'stale A POST cannot fetch detail'); assertHalo('b');
assert.equal(calls.length,clickCalls,'neither POST may replay animated graph-click motion');
assert.deepEqual(pose(),bPose);
// Search A is accepted and starts an animation, then click B takes ownership.
postHook=id=>Promise.resolve(accept(id));
await searchButton('a').onclick(); await flush();
const beforeNewClick=pose(); postHook=id=>new Promise(resolve=>pendingPosts.push({id,resolve}));
const third=clickHandler(b); assertImmediate(beforeNewClick,b);
const manualPosition={x:901,y:802,z:703}, manualTarget={x:91,y:82,z:73};
orbit(manualPosition,manualTarget); const manual=pose(), manualCalls=calls.length;
tick(); tick(); pendingPosts[2].resolve(accept('b')); await third; await flush(); tick(); tick();
assert.deepEqual(pose(),manual,'late acceptance or old search frame cannot override newer orbit');
assert.equal(calls.length,manualCalls); assertHalo('b');
// Conversely a newer search may focus, without replaying an older graph click.
const fourth=clickHandler(a); const newerSearch=searchButton('b').onclick();
pendingPosts[4].resolve(accept('b')); await newerSearch; await flush(); tick(); tick();
const latest=pose(), latestCalls=calls.length;
pendingPosts[3].resolve(accept('a')); await fourth; await flush(); tick(); tick();
assert.deepEqual(pose(),latest); assert.equal(calls.length,latestCalls); assertHalo('b');
assert.deepEqual(details,['b','a','b','b'],'only owned acceptances load detail');
''')

    def test_rejected_post_keeps_clicked_view_without_unaccepted_detail_or_replay(self):
        self.run_scenario(r'''
render(); configureView(); calls.length=0;
let resolvePost; postHook=()=>new Promise(resolve=>{resolvePost=resolve;});
const before=pose(), pending=clickHandler(a);
const clicked=translated(before,a), count=calls.length;
resolvePost({ok:false,status:409,text:async()=>'selection rejected'});
await pending; await flush(); tick(); tick();
assert.deepEqual(details,[],'rejected A never authorizes an A detail GET');
assert.equal(calls.length,count,'rejection never replays focus');
assert.deepEqual(pose(),clicked,'rejection leaves locally centered user view intact');
function textContent(element) {return [element.textContent||'',...element.children.map(textContent)].join(' ');}
assert.match(textContent(elements.detail),/selection rejected|409|failed/i,'selection error is reported');
// A later accepted click owns both detail and halo, even after the failed intent.
postHook=id=>Promise.resolve(accept(id)); const nextBefore=pose();
const next=clickHandler(b); assertImmediate(nextBefore,b); await next; await flush(); tick(); tick();
assert.deepEqual(details,['b']); assertHalo('b');
''')

    def test_invalid_hidden_and_unpositioned_clicks_fail_safely_without_camera_jump(self):
        self.run_scenario(r'''
const bad=node('bad',NaN,0.2,Infinity), origin=node('origin',0,0,0);
const data=model([a,b,bad,origin]); data.unpositioned=[{track_id:'unpositioned'}];
render(data); configureView(); calls.length=0;
const before=pose(), requestCount=requests.length;
for(const invalid of [null,undefined,{}]) {
  let pending; assert.doesNotThrow(()=>{pending=clickHandler(invalid);},'invalid pick must not throw from real handler');
  await pending; await flush(); tick();
}
assert.equal(requests.length,requestCount,'picks without a track id cannot submit selection');
assert.deepEqual(pose(),before);
for(const picked of [bad,node('hidden'),{id:'unpositioned'},{id:'missing'}]) {
  await clickHandler(picked); await flush(); tick(); tick();
  assert.deepEqual(pose(),before,'only mounted visible finite geometry may move the camera');
}
assert.deepEqual(details,['bad','hidden','unpositioned','missing'],'valid selection ids still load detail safely');
assert.equal(calls.length,0,'invalid geometry never emits a camera pose');
const originBefore=pose(); let resolvePost;
postHook=()=>new Promise(resolve=>{resolvePost=resolve;});
const pending=clickHandler(origin); assertImmediate(originBefore,origin);
const centered=pose(); resolvePost(accept('origin')); await pending; await flush(); tick(); tick();
assert.deepEqual(pose(),centered,'finite positioned origin works without radial-direction guess');
assertHalo('origin');
''')


