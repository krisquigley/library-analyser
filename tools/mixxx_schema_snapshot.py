"""Turn Mixxx's public res/schema.xml into the pinned schema the Mixxx export creates (#133).

Mixxx builds its library database by running each <revision>'s SQL in order. This tool does the same in an
empty in-memory SQLite database and writes the resulting schema (every table and index, in creation order)
as one SQL file, headed by where it came from. It reads only the schema.xml it is given: never a Mixxx
database. Run it once per supported Mixxx release, with schema.xml downloaded from that release's tag.

    python -m tools.mixxx_schema_snapshot --schema-xml schema.xml \\
        --source "mixxxdj/mixxx 2.5.6 (commit 3ebac44…) res/schema.xml" --output mixxx-2.5-schema.sql
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import sqlite3
import xml.etree.ElementTree as ElementTree


class SchemaSnapshotError(ValueError):
    pass


@dataclass(frozen=True)
class SchemaSnapshot:
    revision: int
    min_compatible: int
    sql: str


def schema_snapshot(schema_xml: str, *, source: str) -> SchemaSnapshot:
    revisions = ElementTree.fromstring(schema_xml).findall('revision')
    if not revisions:
        raise SchemaSnapshotError('schema.xml has no <revision> elements')
    database = sqlite3.connect(':memory:')
    for revision in revisions:
        for statement in revision.iter('sql'):
            if statement.text and statement.text.strip():
                try:
                    database.executescript(statement.text)
                except sqlite3.Error as error:
                    raise SchemaSnapshotError(f'revision {revision.get("version")}: {error}') from error
    last = revisions[-1]
    version = int(last.get('version'))
    min_compatible = int(last.get('min_compatible', version))
    objects = database.execute("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
                               'ORDER BY rowid').fetchall()
    header = [f'-- Mixxx library schema, generated by tools/mixxx_schema_snapshot.py (#133).',
              f'-- Source: {source}',
              f'-- Schema revision: {version} (min_compatible {min_compatible})',
              '-- Derived from Mixxx, which is GPL-2.0-or-later; see NOTICE and LICENSE.mixxx beside this file.']
    return SchemaSnapshot(version, min_compatible, '\n'.join(header + [row[0] + ';' for row in objects]) + '\n')


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--schema-xml', type=Path, required=True)
    parser.add_argument('--source', required=True, help='repository, release, commit and path of the schema.xml')
    parser.add_argument('--output', type=Path, required=True, help='a new file')
    args = parser.parse_args(argv)
    if args.output.exists():
        parser.error(f'{args.output} already exists')
    snapshot = schema_snapshot(args.schema_xml.read_text(encoding='utf-8'), source=args.source)
    args.output.write_text(snapshot.sql, encoding='utf-8')
    print(f'Schema revision {snapshot.revision} (min_compatible {snapshot.min_compatible}) written to {args.output}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
